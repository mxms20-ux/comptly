/* =============================================
   ESTADO
   ============================================= */

let catActiva = "All";
let idx = 0;
let lang = "en";

const POR_PAG = 4;


/* =============================================
   NAVBAR
   ============================================= */

window.addEventListener("scroll", () => {
  document
    .getElementById("navbar")
    .classList.toggle("scrolled", window.scrollY > 20);
});

